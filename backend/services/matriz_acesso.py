"""Matriz fechada: códigos de ação e escopo máximo por perfil padrão."""
EMPRESA = 'empresa'
PROPRIO = 'proprio'
ATRIBUICAO = 'atribuicao'

ADMINISTRACAO = frozenset({
    'USUARIO_CRIAR', 'USUARIO_VISUALIZAR', 'USUARIO_EDITAR', 'USUARIO_DESATIVAR',
    'CARGO_CRIAR', 'CARGO_VISUALIZAR', 'CARGO_EDITAR', 'PERFIL_CRIAR',
    'PERFIL_VISUALIZAR', 'PERFIL_EDITAR', 'PERFIL_PERMISSAO_GERENCIAR',
})
OPERACOES = frozenset({
    'MAQUINA_CRIAR', 'MAQUINA_VISUALIZAR', 'MAQUINA_EDITAR', 'MAQUINA_DESATIVAR',
    'EQUIPAMENTO_CRIAR', 'EQUIPAMENTO_VISUALIZAR', 'EQUIPAMENTO_EDITAR', 'EQUIPAMENTO_DESATIVAR',
    'OS.CRIAR', 'OS.VISUALIZAR', 'OS.EDITAR', 'OS.CANCELAR', 'OS.CONCLUIR',
    'MANUTENCAO.CRIAR', 'MANUTENCAO.VISUALIZAR', 'MANUTENCAO.EDITAR', 'MANUTENCAO.CONCLUIR', 'MANUTENCAO.CANCELAR',
    'INDISPONIBILIDADE.CRIAR', 'INDISPONIBILIDADE.VISUALIZAR', 'INDISPONIBILIDADE.EDITAR',
    'DASHBOARD.VISUALIZAR',
})
LEITURA = frozenset(p for p in ADMINISTRACAO | OPERACOES if p.endswith(('VISUALIZAR',)))

def _empresa(codigos):
    return dict.fromkeys(codigos, EMPRESA)

MATRIZ = {
    'ADMIN_EMPRESA': _empresa(ADMINISTRACAO | OPERACOES),
    'DIRETORIA': _empresa(LEITURA),
    'GESTOR_FROTA': _empresa(OPERACOES | {'USUARIO_VISUALIZAR'}),
    'ADMINISTRATIVO': _empresa({'USUARIO_VISUALIZAR', 'CARGO_VISUALIZAR', 'PERFIL_VISUALIZAR', 'MAQUINA_VISUALIZAR', 'EQUIPAMENTO_VISUALIZAR', 'OS.VISUALIZAR', 'INDISPONIBILIDADE.VISUALIZAR', 'DASHBOARD.VISUALIZAR'}),
    'MANUTENCAO': {**_empresa({'MAQUINA_VISUALIZAR', 'EQUIPAMENTO_VISUALIZAR'}), **dict.fromkeys({'OS.VISUALIZAR', 'OS.EDITAR', 'OS.CONCLUIR', 'MANUTENCAO.CRIAR', 'MANUTENCAO.VISUALIZAR', 'MANUTENCAO.EDITAR', 'MANUTENCAO.CONCLUIR', 'INDISPONIBILIDADE.VISUALIZAR'}, ATRIBUICAO)},
    'OPERADOR': {**_empresa({'MAQUINA_VISUALIZAR', 'EQUIPAMENTO_VISUALIZAR'}), **dict.fromkeys({'OS.CRIAR', 'OS.VISUALIZAR', 'INDISPONIBILIDADE.CRIAR', 'INDISPONIBILIDADE.VISUALIZAR'}, ATRIBUICAO)},
    'AUDITOR': _empresa(LEITURA),
}
for _permissoes in MATRIZ.values():
    _permissoes['USUARIO_PROPRIO_VISUALIZAR'] = PROPRIO

for _perfil in ('ADMIN_EMPRESA', 'AUDITOR'):
    MATRIZ[_perfil]['AUDITORIA.VISUALIZAR'] = EMPRESA

